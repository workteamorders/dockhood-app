#!/usr/bin/env node
import { readFileSync, realpathSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(dirname(fileURLToPath(import.meta.url)));

/** Read-only RPC validation; no deployment, signing or transaction submission. */
export async function renderTestnetConfig({ env = process.env, fetchImpl = fetch, directory = here } = {}) {
  const required = (key) => {
    const value = env[key]?.trim();
    if (!value) throw new Error(`${key} is required`);
    return value;
  };
  const factory = required('TESTNET_FACTORY_ADDRESS');
  if (!/^0x[0-9a-fA-F]{40}$/.test(factory) || /^0x0{40}$/i.test(factory)) {
    throw new Error('TESTNET_FACTORY_ADDRESS must be a nonzero EVM address');
  }
  const start = required('TESTNET_START_BLOCK');
  if (!/^[1-9][0-9]*$/.test(start) || !Number.isSafeInteger(Number(start))) {
    throw new Error('TESTNET_START_BLOCK must be a positive safe integer in decimal');
  }
  const rpc = required('TESTNET_RPC_URL');
  let url;
  try {
    url = new URL(rpc);
  } catch {
    throw new Error('TESTNET_RPC_URL must be an absolute HTTP(S) URL');
  }
  if (!['http:', 'https:'].includes(url.protocol) || url.hash || rpc.includes('${')) {
    throw new Error('TESTNET_RPC_URL must be an HTTP(S) URL without a fragment or env interpolation');
  }

  let response;
  try {
    response = await fetchImpl(rpc, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'eth_chainId', params: [] }),
      signal: AbortSignal.timeout(10_000),
    });
  } catch {
    // Do not leak credentials embedded in the RPC URL through fetch's error message.
    throw new Error('TESTNET_RPC_URL chain ID request failed or timed out');
  }
  if (!response.ok) throw new Error(`TESTNET_RPC_URL returned HTTP ${response.status}`);
  let payload;
  try {
    payload = await response.json();
  } catch {
    throw new Error('TESTNET_RPC_URL returned invalid JSON');
  }
  if (payload?.jsonrpc !== '2.0' || payload.id !== 1 || payload.error ||
      typeof payload.result !== 'string' || !/^0x[0-9a-f]+$/i.test(payload.result)) {
    throw new Error('TESTNET_RPC_URL returned an invalid eth_chainId response');
  }
  if (BigInt(payload.result) !== 46630n) throw new Error('TESTNET_RPC_URL must report Robinhood testnet chain ID 46630');

  // Preserve the canonical global contract declarations verbatim, without a second set of ABIs/events.
  const main = readFileSync(join(directory, 'config.yaml'), 'utf8');
  const parts = main.split(/^chains:\s*$/m);
  if (parts.length !== 2 || !/^contracts:\s*$/m.test(parts[0]) || !/^name: .+$/m.test(parts[0])) {
    throw new Error('config.yaml must contain one top-level name, contracts and chains section');
  }
  const declarations = parts[0].replace(/^#.*\n/gm, '').replace(/^name: .+$/m, 'name: dockhood-testnet');
  return '# Generated by scripts/render-testnet.mjs after RPC chain ID validation. Do not commit.\n' +
    '# yaml-language-server: $schema=./node_modules/envio/evm.schema.json\n' + declarations +
    'chains:\n' +
    '  - id: 46630\n' +
    `    start_block: ${start}\n` +
    '    rpc:\n' +
    `      url: ${JSON.stringify(rpc)}\n` +
    '      for: sync\n' +
    '    contracts:\n' +
    '      - name: PonsV2Factory\n' +
    `        address: ${JSON.stringify(factory)}\n` +
    '      - name: PonsV2Curve\n';
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  try {
    const config = await renderTestnetConfig();
    const output = join(here, 'config.testnet.local.yaml');
    writeFileSync(`${output}.tmp`, config, { mode: 0o600, flag: 'wx' });
    renameSync(`${output}.tmp`, output);
    console.log('Rendered config.testnet.local.yaml for chain 46630 (RPC sync).');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
